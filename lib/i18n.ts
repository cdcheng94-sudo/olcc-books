// Widened type so T.zh and T.en are interchangeable. (Without this, `as const`
// would make every literal string its own type and the two languages would
// be incompatible at the Dict level.)
export type Dict = typeof T.zh;

/**
 * Helper for strings with {placeholder} tokens. Pass the template and a
 * map of names → values; returns the filled string.
 *
 *   interp(t.invoice.confirmDelete, { number: "INV-0001" })
 *     => "Delete invoice INV-0001? This cannot be undone."
 */
export function interp(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll("{" + k + "}", String(v)),
    template,
  );
}
